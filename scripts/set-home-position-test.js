'use strict';
const assert=require('node:assert/strict');
const fs=require('node:fs');
const os=require('node:os');
const path=require('node:path');
const {spawnSync}=require('node:child_process');
const dir=fs.mkdtempSync(path.join(os.tmpdir(),'beacon-position-cli-'));
const file=path.join(dir,'private-home-position.json');
const script=path.join(__dirname,'set-home-position.js');
assert.ok(fs.existsSync(script),'Owner-only local home-position entry is not implemented');
const run=input=>spawnSync(process.execPath,[script],{input,encoding:'utf8',env:{...process.env,DADRADAR_HOME_POSITION_FILE:file}});
let result=run('35.123456789\n-82.987654321\n');
assert.equal(result.status,0,result.stderr);
assert.deepEqual(JSON.parse(fs.readFileSync(file,'utf8')),{latitude:35.123456789,longitude:-82.987654321});
assert.ok(!result.stdout.includes('35.123456789')&&!result.stdout.includes('-82.987654321'),'CLI must not print entered coordinates');
result=run('\n-82\n');assert.notEqual(result.status,0);
assert.deepEqual(JSON.parse(fs.readFileSync(file,'utf8')),{latitude:35.123456789,longitude:-82.987654321});
result=run('91\n4\n');assert.notEqual(result.status,0);
console.log('Private home-position local entry passed: no argument history, no coordinate output, invalid input preserves setting.');
