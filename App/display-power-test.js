"use strict";
const assert = require("node:assert/strict"), fs = require("node:fs"), path = require("node:path");
const file = path.join(__dirname, "display-power.js");
assert(!fs.readFileSync(file,"utf8").includes('screen.style.transform=`scale('),"CRT optics must not scale the live map's camera measurement bounds");
assert(fs.readFileSync(file,"utf8").includes('["#flight-number,#flight-origin,#flight-destination,#status-value","flaps"]'),"Flap apertures must measure real groups, not their zero-box display:contents parent");
const api = fs.existsSync(file) ? require(file) : {};
assert.equal(typeof api.crtPresentation, "function", "CRT presentation adapter must exist");
const s = (state, progress, elapsed = 0) => ({state, progress, elapsed, duration: state === "starting" ? 5000 : 2400, reducedMotion:false});
assert.deepEqual(api.crtPresentation(s("on", 1)), {x:1,y:1,light:1,dot:0,blur:0,raster:0,bloom:0});
assert.equal(api.crtPresentation(s("off", 0)).light, 0);
const dot = api.crtPresentation(s("stopping", .1, 2160));
assert.equal(dot.light, 0); assert(dot.dot > 0, "Shutdown dot lingers after picture collapse");
const bloom = api.crtPresentation(s("starting", .05, 250));
assert.equal(bloom.x,1); assert.equal(bloom.y,1); assert.equal(bloom.dot,0,"Startup warms a full-size raster without center growth");
const reduced = api.crtPresentation({...s("starting", .5, 90),reducedMotion:true});
assert.equal(reduced.x, 1); assert.equal(reduced.y, 1); assert.equal(reduced.raster, 0);
let touched = false;
const doc = {documentElement:{hasAttribute:()=>true}, createElement(){touched=true;}};
assert.equal(api.mount({document:doc}), null); assert.equal(touched, false, "Family mount must be inert");
console.log("CRT presentation and primary-only gating tests passed.");
assert.equal(typeof api.moduleLight,"function","Registered local lamp staging must exist");
assert.equal(api.moduleLight(s("off",0),"paper"),0);
assert.equal(api.moduleLight(s("on",1),"weekly",6),1);
assert(api.moduleLight(s("starting",.2),"paper")>0);
assert(api.moduleLight(s("starting",.2),"clocks")>.8,"Clock illumination precedes mechanical movement");
assert(api.moduleLight(s("starting",.36),"weekly",0)>api.moduleLight(s("starting",.36),"weekly",6));
assert.equal(typeof api.needlePresentation,"function","Needle sweep must be presentation-only");
assert.equal(api.needlePresentation(s("on",1),83),83);
assert.equal(api.needlePresentation(s("off",0),83),0);
assert.equal(api.needlePresentation(s("starting",.8),117),117,"Newest instrument reading settles without cached flight data");
assert.equal(api.needlePresentation({...s("starting",.3),reducedMotion:true},83),83,"Reduced motion has no sweep");
assert.equal(typeof api.apertureContains,"function","Overlapping map/counter apertures must reveal their union, not XOR");
const apertures=[{left:534,top:229,right:1500,bottom:844},{left:520,top:742,right:782,bottom:839}];
assert.equal(api.apertureContains(apertures,{x:650,y:790}),true,"Counter inside map remains a genuine opening");
assert.equal(api.apertureContains(apertures,{x:525,y:790}),true,"Counter overhang stays open");
assert.equal(api.apertureContains(apertures,{x:500,y:790}),false);
